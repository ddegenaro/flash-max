import torch
from torch import Tensor

c = 1.0

def u(t: Tensor, x: Tensor, y: Tensor, z: Tensor) -> Tensor:
	r_sq = x**2+y**2+z**2

	E_x = 6*(-1/3*x**3*z+2/3*t*x**2*y+z*(t**2-1/3*y**2-1/3*z**2)*x+2/3*t*y*(y**2+z**2))/(r_sq)**(5/2)
	E_y =  6*(-1/3*y**3*z-2/3*t*x*y**2+z*(t**2-1/3*x**2-1/3*z**2)*y-2/3*t*x*(x**2+z**2))/(r_sq)**(5/2)
	E_z =  (-2*x**4+(-2*t**2-4*y**2-6*z**2)*x**2-2*y**4+(-2*t**2-6*z**2)*y**2+4*t**2*z**2-4*z**4)/(r_sq)**(5/2)
	B_x =  6*(-1/3*x**3*z-2/3*t*x**2*y+z*(t**2-1/3*y**2-1/3*z**2)*x-2/3*t*y*(y**2+z**2))/(r_sq)**(5/2)
	B_y =  6*(-1/3*y**3*z+2/3*t*x*y**2+z*(t**2-1/3*x**2-1/3*z**2)*y+2/3*t*x*(x**2+z**2))/(r_sq)**(5/2)
	B_z =  (-2*x**4+(-2*t**2-4*y**2-6*z**2)*x**2-2*y**4+(-2*t**2-6*z**2)*y**2+4*t**2*z**2-4*z**4)/(r_sq)**(5/2)

	return torch.vstack((E_x, E_y, E_z, B_x, B_y, B_z))