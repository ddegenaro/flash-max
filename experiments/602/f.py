import torch
from torch import Tensor

c = 1.

def u(t: Tensor, x: Tensor, y: Tensor, z: Tensor) -> Tensor:
    Ex = (
    ( (1 + x**2 + y**2 + z**2 - t**2)**3 - 12*t**2*(1 + x**2 + y**2 + z**2 - t**2) )
    * ( (t - z)**2 - 1 - x**2 + y**2 )
    - ( 8*t**3 - 6*t*(1 + x**2 + y**2 + z**2 - t**2)**2 )
    * ( 2*x*y - 2*(t - z) )
    ) / ( ((1 + x**2 + y**2 + z**2 - t**2)**2 + 4*t**2)**3 )

    Ey = (
    ( (1 + x**2 + y**2 + z**2 - t**2)**3 - 12*t**2*(1 + x**2 + y**2 + z**2 - t**2) )
    * ( -2*x*y - 2*(t - z) )
    - ( 8*t**3 - 6*t*(1 + x**2 + y**2 + z**2 - t**2)**2 )
    * ( 1 - (t - z)**2 - x**2 + y**2 )
    ) / ( ((1 + x**2 + y**2 + z**2 - t**2)**2 + 4*t**2)**3 )

    Ez = (
    ( (1 + x**2 + y**2 + z**2 - t**2)**3 - 12*t**2*(1 + x**2 + y**2 + z**2 - t**2) )
    * ( 2*x*(t - z) - 2*y )
    + ( 8*t**3 - 6*t*(1 + x**2 + y**2 + z**2 - t**2)**2 )
    * ( 2*x + 2*y*(t - z) )
    ) / ( ((1 + x**2 + y**2 + z**2 - t**2)**2 + 4*t**2)**3 )

    Bx = (
    ( 8*t**3 - 6*t*(1 + x**2 + y**2 + z**2 - t**2)**2 )
    * ( (t - z)**2 - 1 - x**2 + y**2 )
    + ( (1 + x**2 + y**2 + z**2 - t**2)**3 - 12*t**2*(1 + x**2 + y**2 + z**2 - t**2) )
    * ( 2*x*y - 2*(t - z) )
    ) / ( ((1 + x**2 + y**2 + z**2 - t**2)**2 + 4*t**2)**3 )

    By = (
    ( 8*t**3 - 6*t*(1 + x**2 + y**2 + z**2 - t**2)**2 )
    * ( -2*x*y - 2*(t - z) )
    + ( (1 + x**2 + y**2 + z**2 - t**2)**3 - 12*t**2*(1 + x**2 + y**2 + z**2 - t**2) )
    * ( 1 - (t - z)**2 - x**2 + y**2 )
    ) / ( ((1 + x**2 + y**2 + z**2 - t**2)**2 + 4*t**2)**3 )

    Bz = (
    ( 8*t**3 - 6*t*(1 + x**2 + y**2 + z**2 - t**2)**2 )
    * ( 2*x*(t - z) - 2*y )
    - ( (1 + x**2 + y**2 + z**2 - t**2)**3 - 12*t**2*(1 + x**2 + y**2 + z**2 - t**2) )
    * ( 2*x + 2*y*(t - z) )
    ) / ( ((1 + x**2 + y**2 + z**2 - t**2)**2 + 4*t**2)**3 )
    
    return torch.vstack((Ex, Ey, Ez, Bx, By, Bz))